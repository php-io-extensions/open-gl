function synthTypedef(array $p): string
{
    $args = [];
    foreach ($p['args'] as $a) {
        $args[] = $a['type'] . ' ' . cName($a['name']);
    }
    $argSrc = $args === [] ? 'void' : implode(', ', $args);

    return "typedef {$p['ret']} (*{$p['pfn']})({$argSrc});";
}

